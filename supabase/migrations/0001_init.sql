-- ---------- admins (by login e-mail) ----------
-- Add an admin: insert their e-mail here, then create the user in Supabase → Authentication → Users.
create table if not exists public.admin_emails (
  email text primary key check (email = lower(email)),
  created_at timestamptz not null default now()
);
alter table public.admin_emails enable row level security;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = ''
as $$ select exists (
  select 1 from public.admin_emails a
  where a.email = lower(coalesce((select auth.jwt()) ->> 'email', ''))
) $$;

create policy "admin emails read" on public.admin_emails for select to authenticated using ((select public.is_admin()));
create policy "admin emails insert" on public.admin_emails for insert to authenticated with check ((select public.is_admin()));
create policy "admin emails delete" on public.admin_emails for delete to authenticated
  using ((select public.is_admin()) and email <> lower(coalesce((select auth.jwt()) ->> 'email', '')));

