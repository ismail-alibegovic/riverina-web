-- ---------- public read: one JSON document ----------
create or replace function public.public_site_data()
returns jsonb language sql stable security definer set search_path = ''
as $$
  with s as (select coalesce((select data from public.site_content where key = 'settings'), '{}'::jsonb) d)
  select jsonb_build_object(
    'settings', (select d from s),
    'page', coalesce((select data from public.site_content where key = 'page'), '{}'::jsonb),
    'scenes', coalesce((select data from public.site_content where key = 'scenes'), '{"masterplan":{"views":[]},"buildings":[]}'::jsonb),
    'units', coalesce((
      select jsonb_agg(jsonb_build_object(
        'code', u.code, 'building', u.building, 'floor', u.floor, 'bedrooms', u.bedrooms,
        'area', u.area, 'area_net', u.area_net, 'orientation', u.orientation, 'status', u.status,
        'price', case when coalesce(((select d from s)->>'show_price')::boolean, false) and u.status <> 'sold' then u.price else null end,
        'type_label', u.type_label, 'plan', u.plan_path, 'pdf', u.pdf_path,
        'rooms', u.rooms, 'extra', u.extra, 'description', u.description
      ) order by u.building, u.floor, u.code)
      from public.units u where not u.hidden), '[]'::jsonb)
  )
$$;
grant execute on function public.public_site_data() to anon, authenticated;

-- ---------- public write: enquiries ----------
create or replace function public.submit_lead(p jsonb)
returns bigint language plpgsql security definer set search_path = ''
as $$
declare
  v_name text := left(trim(coalesce(p->>'name', '')), 190);
  v_email text := left(lower(trim(coalesce(p->>'email', ''))), 190);
  v_phone text := left(trim(coalesce(p->>'phone', '')), 64);
  new_id bigint;
begin
  if coalesce(p->>'website', '') <> '' then return 0; end if; -- honeypot
  if v_name = '' or (v_email = '' and v_phone = '') or coalesce((p->>'consent')::boolean, false) = false then
    raise exception 'missing fields';
  end if;
  if v_email <> '' and v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then raise exception 'bad email'; end if;
  if (select count(*) from public.leads l where l.created_at > now() - interval '10 minutes'
        and ((v_email <> '' and l.email = v_email) or (v_phone <> '' and l.phone = v_phone))) >= 3 then
    raise exception 'rate limited';
  end if;
  if (select count(*) from public.leads l where l.created_at > now() - interval '1 minute') >= 20 then
    raise exception 'rate limited';
  end if;
  insert into public.leads (building, unit, name, email, phone, message, lang, page)
  values (left(coalesce(p->>'building', ''), 64), left(coalesce(p->>'unit', ''), 64), v_name, v_email, v_phone,
          left(coalesce(p->>'message', ''), 4000), left(coalesce(p->>'lang', ''), 8), left(coalesce(p->>'page', ''), 500))
  returning id into new_id;
  return new_id;
end $$;
grant execute on function public.submit_lead(jsonb) to anon, authenticated;


